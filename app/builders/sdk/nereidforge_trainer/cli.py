def _cmd_validate(args: argparse.Namespace) -> int:
    try:
        with open(args.path, encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"cannot read {args.path}: {exc}", file=sys.stderr)
        return 2
    errors = validate_profile(doc)
    if errors:
        for error in errors:
            print(f"FAIL  {error}", file=sys.stderr)
        return 1
    print(f"OK    {args.path}")
    return 0


def _cmd_validate_metrics(args: argparse.Namespace) -> int:
    """_cmd_validate_metrics validates a document without importing trainer code."""
    try:
        with open(args.path, encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"cannot read {args.path}: {exc}", file=sys.stderr)
        return 2
    errors = validate_training_metrics(doc)
    if errors:
        for error in errors:
            print(f"FAIL  {error}", file=sys.stderr)
        return 1
    print(f"OK    {args.path}")
    return 0


def _cmd_profile(args: argparse.Namespace) -> int:
    with open(args.path, encoding="utf-8") as fh:
        doc = json.load(fh)
    print(json.dumps(doc, indent=2))
    return 0


def _cmd_init(args: argparse.Namespace) -> int:
    target = os.path.abspath(args.directory)
    if os.path.exists(target) and os.listdir(target):
        print(f"refusing to write into non-empty directory: {target}", file=sys.stderr)
        return 1
    os.makedirs(target, exist_ok=True)

    framework = {"name": args.framework, "version": args.framework_version or "*"}
    from . import __version__ as sdk_version

    files = {
        "train.py": TRAIN_TEMPLATE.format(
            name=args.name,
            task=args.task,
            architecture=args.architecture,
            framework=args.framework,
        ),
        "trainer_profile.py": PROFILE_MODULE_TEMPLATE.format(
            name=args.name,
            schema=PROFILE_SCHEMA,
            framework_json=json.dumps(framework),
            task=args.task,
            task_label=args.task.replace("_", " ").title(),
            architecture=args.architecture,
        ),
        "nf_profile.py": PROFILE_TEMPLATE,
        "Dockerfile": DOCKERFILE_TEMPLATE.format(sdk_version=sdk_version),
        "README.md": README_TEMPLATE.format(
            name=args.name,
            slug=args.name.replace("/", "-"),
            sdk_version=sdk_version,
        ),
        ".gitignore": "__pycache__/\n*.pyc\n",
    }
    for name, content in files.items():
        with open(os.path.join(target, name), "w", encoding="utf-8") as fh:
            fh.write(content)

    # The committed announcement, generated from the same source the image uses.
    module_path = os.path.join(target, "trainer_profile.py")
    spec = importlib.util.spec_from_file_location("trainer_profile", module_path)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        print(f"cannot load {module_path}", file=sys.stderr)
        return 1
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    document = module.profile()
    with open(os.path.join(target, "trainer-profile.json"), "w", encoding="utf-8") as fh:
        json.dump(document, fh, indent=2)
        fh.write("\n")

    print(f"created {target}")
    print("next: fill in train.py, install your framework, build and register.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="nf-trainer", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    validate = sub.add_parser("validate", help="validate a trainer-profile.json")
    validate.add_argument("path")
    validate.set_defaults(func=_cmd_validate)

    validate_metrics = sub.add_parser(
        "validate-metrics", help="validate an <artifact-id>.metrics.json",
    )
    validate_metrics.add_argument("path")
    validate_metrics.set_defaults(func=_cmd_validate_metrics)

    show = sub.add_parser("profile", help="print a trainer-profile.json")
    show.add_argument("path")
    show.set_defaults(func=_cmd_profile)

    init = sub.add_parser("init", help="scaffold a custom trainer")
    init.add_argument("directory")
    init.add_argument("--name", required=True, help="profile name, e.g. acme/yolo")
    init.add_argument("--task", default="detection")
    init.add_argument("--architecture", default="custom")
    init.add_argument("--framework", default="custom")
    init.add_argument("--framework-version", default="")
    init.set_defaults(func=_cmd_init)

    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
