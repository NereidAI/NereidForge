"""`nf-trainer` — component-author CLI (profile validation + custom trainer scaffold).

    nf-trainer validate trainer-profile.json
    nf-trainer validate-metrics job-123.metrics.json
    nf-trainer profile trainer-profile.json
    nf-trainer init ../my-trainer --name acme/yolo --task detection

`init` writes a *skeleton* that already satisfies the platform contract (env,
artifacts, profile) and leaves exactly one thing to fill in: the model. It never
adds a framework dependency — that choice, and its licence, belong to whoever
builds the image (ADR-016 D-02).
"""

